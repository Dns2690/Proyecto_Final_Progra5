    /** Converts the text into a price, or null when it is not valid. */
    private BigDecimal leerPrecio(String texto) {
        try {
            BigDecimal precio = new BigDecimal(texto.trim());
            return precio.compareTo(BigDecimal.ZERO) > 0 ? precio : null;
        } catch (Exception e) {
            return null;
        }
    }

